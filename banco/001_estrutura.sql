SET SQL DIALECT 3;
SET BAIL ON;

CREATE TABLE ESTADO (
  ID INTEGER NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  UF CHAR(2) NOT NULL,
  CONSTRAINT PK_ESTADO PRIMARY KEY (ID),
  CONSTRAINT UQ_ESTADO_UF UNIQUE (UF)
);

CREATE TABLE CIDADE (
  ID INTEGER NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  ESTADOID INTEGER NOT NULL,
  CONSTRAINT PK_CIDADE PRIMARY KEY (ID),
  CONSTRAINT FK_CIDADE_ESTADO FOREIGN KEY (ESTADOID) REFERENCES ESTADO (ID),
  CONSTRAINT UQ_CIDADE_NOME_ESTADO UNIQUE (NOME, ESTADOID)
);

CREATE TABLE CLIENTE (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME VARCHAR(80) NOT NULL,
  CEP CHAR(8) NOT NULL,
  CPF_CNPJ VARCHAR(14) NOT NULL,
  ENDERECO VARCHAR(100),
  NUMERO VARCHAR(20),
  COMPLEMENTO VARCHAR(60),
  BAIRRO VARCHAR(100),
  CIDADE INTEGER NOT NULL,
  DATANASCIMENTO DATE,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
  CONSTRAINT FK_CLIENTE_CIDADE FOREIGN KEY (CIDADE) REFERENCES CIDADE (ID),
  CONSTRAINT CK_CLIENTE_DOCUMENTO CHECK (CHAR_LENGTH(CPF_CNPJ) IN (11, 14))
);

CREATE INDEX IX_CLIENTE_NOME ON CLIENTE (NOME);
CREATE INDEX IX_CLIENTE_DOCUMENTO ON CLIENTE (CPF_CNPJ);
CREATE INDEX IX_CLIENTE_CEP ON CLIENTE (CEP);
CREATE INDEX IX_CLIENTE_NASCIMENTO ON CLIENTE (DATANASCIMENTO);

CREATE EXCEPTION EX_CLIENTE_PROTEGIDO 'Este cliente nao pode ser excluido.';
SET TERM ^ ;
CREATE TRIGGER TR_CLIENTE_PROTEGER_EXCLUSAO FOR CLIENTE
ACTIVE BEFORE DELETE POSITION 0
AS
BEGIN
  IF (OLD.ID IN (1, 5, 8, 10, 15)) THEN
    EXCEPTION EX_CLIENTE_PROTEGIDO;
END^
SET TERM ; ^
COMMIT;
